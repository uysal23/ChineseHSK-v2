PUNCT = set("，。？！；：、,.?!;:（）()《》“”‘’—… ")
INTERJECTION_PINYIN = {"嗯": "èn", "哦": "ò", "啊": "a", "哎": "āi", "欸": "éi"}

def pick(options, key):
    h = hashlib.sha256(key.encode("utf-8")).digest()
    return options[int.from_bytes(h[:4], "big") % len(options)]

def pinyin_word(word):
    if word in INTERJECTION_PINYIN:
        return INTERJECTION_PINYIN[word]
    syllables = lazy_pinyin(
        word,
        style=Style.TONE,
        neutral_tone_with_five=False,
        errors="default",
        strict=False,
    )
    return "".join(syllables)

def to_pinyin(text):
    text = t2s.convert(text)
    tokens = []
    buf = ""
    for ch in text:
        if ch in PUNCT:
            if buf:
                tokens.extend(jieba.cut(buf, HMM=False))
                buf = ""
            tokens.append(ch)
        else:
            buf += ch
    if buf:
        tokens.extend(jieba.cut(buf, HMM=False))

    out = []
    for tok in tokens:
        if tok in PUNCT:
            out.append(tok)
        elif re.search(r"[\u3400-\u9fff]", tok):
            out.append(pinyin_word(tok))
        else:
            out.append(tok)

    s = " ".join(out)
    s = re.sub(r"\s+([，。？！；：、,.?!;:）)])", r"\1", s)
    s = re.sub(r"([（(《“‘])\s+", r"\1", s)
    s = s.replace("，", ",").replace("。", ".").replace("？", "?").replace("！", "!")
    s = s.replace("；", ";").replace("：", ":")
    s = re.sub(r"\s+", " ", s).strip()
    for i, c in enumerate(s):
        if c.isalpha():
            s = s[:i] + c.upper() + s[i+1:]
            break
    return s

